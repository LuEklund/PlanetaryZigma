    pub fn Proc(func: Func) type {
        if (!@inComptime()) {}
        return struct {
            pub const name = std.fmt.comptimePrint("PFN_vk{c}{s}", .{ std.ascii.toUpper(@tagName(func)[0]), @tagName(func)[1..] });
            pub const PFN: type = pfn: {
                if (!@hasDecl(c, name)) @compileError("Expected Vulkan PFN type '" ++ name ++ "' to exist in the C bindings (name generated from '" ++ name ++ "')");
                break :pfn @field(c, name);
            };

            pub const Inner: type = switch (@typeInfo(PFN)) {
                .optional => |optional| optional.child,
                else => |T| T,
            };

            pub fn load(instance: anytype) !Inner {
                const ptr = c.vkGetInstanceProcAddr(instance.handle, name) orelse @panic("failed to find proc " ++ @tagName(func));
                return @ptrCast(ptr);
            }
        };
    }
};
